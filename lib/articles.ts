/** «20 сентября 2026 года» для текста на странице. */
export function articleDate(iso: string): string {
  return new Date(`${iso}T00:00:00+05:00`).toLocaleDateString("ru-RU", {
    day: "numeric",
    month: "long",
    year: "numeric",
    timeZone: "Asia/Almaty",
  });
}
